export async function seedSystem(db: Db) {
  const [{ n }] = (await db.execute(
    sql`select count(*)::int as n from system_records`,
  )) as unknown as { n: number }[]; // postgres-js returns rows as an array
  if (n > 0) return;
  const now = new Date().toISOString();
  const rows: { kind: string; id: string; pos: number; data: unknown }[] = [];
  const add = <T>(kind: string, list: readonly T[], key: (x: T) => string) =>
    list.forEach((x, i) =>
      rows.push({
        kind,
        id: key(x),
        pos: i + 1,
        data: remap(structuredClone(x)),
      }),
    );

  add("changes", W.CHANGES, (c) => c.id);
  add(
    "reviews",
    [
      W.REVIEWS[0],
      {
        ...W.REVIEWS[1],
        stats: { total: 99, kept: 91, removed: 6, suspended: 2 },
      },
    ],
    (c) => c.id,
  );
  add("waivers", W.WAIVERS, (c) => c.id);
  add("serviceAccounts", W.SERVICE_ACCOUNTS, (c) => c.id);
  add("integrations", W.INTEGRATIONS, (c) => c.key);
  add("templates", W.TEMPLATES, (c) => c.key);
  add("rules", W.EVENT_RULES, (c) => c.event);
  add("deliveries", W.DELIVERIES, (c) => c.id);
  add("budgets", W.BUDGETS, (c) => c.channel);
  add("processors", W.PROCESSORS, (c) => c.id);
  add("retention", W.RETENTION, (c) => c.category);
  const subj: Record<string, string | null | undefined> = {
    "HBZ-C-000101": W.CLIENT_IDS[0],
    "HBZ-C-000103": W.CLIENT_IDS[2],
  };
  const order = ["received", "verifying", "in_progress", "completed"];
  add(
    "dsrs",
    W.DSRS.map((d) => {
      const upto = d.status === "rejected" ? 1 : order.indexOf(d.status) + 1;
      return {
        ...d,
        subjectId: subj[d.subjectNo] ?? undefined,
        version: 1,
        events: order
          .slice(0, upto)
          .map((s, i) => ({
            status: s,
            at: new Date(
              Date.parse(d.receivedAt) + i * 26 * 3600_000,
            ).toISOString(),
          })),
      };
    }),
    (d) => d.id,
  );
  add(
    "components",
    W.COMPONENTS.filter(
      (c) =>
        !["api", "worker", "db", "redis", "storage", "queues"].includes(c.key),
    ),
    (c) => c.key,
  );
  add("backups", W.BACKUPS, (c) => c.id);
  add("drills", W.DRILLS, (c) => c.id);
  add("incidents", W.INCIDENTS, (c) => c.id);
  add("dependencies", W.DEPENDENCIES, (c) => c.id);
  add("posture", W.POSTURE, (c) => c.id);
  add("alerts", W.ALERTS, (c) => c.id);
  add("settings", Object.values(W.SETTING_VALUES), (c) => c.key);

  // IAM overlay for the seeded people.
  const existing = new Set(
    (await db.select({ id: users.userId }).from(users)).map((r) => r.id),
  );
  const meta = W.USERS.filter(
    (u) => existing.has(uid(u.id)) || ("isBootstrap" in u && u.isBootstrap),
  ).map((u) => ({
    id: uid(u.id),
    version: 1,
    createdBy: "createdBy" in u ? u.createdBy : undefined,
    managerName: "managerName" in u ? u.managerName : undefined,
    isBootstrap: ("isBootstrap" in u && u.isBootstrap) || undefined,
    status: u.status === "active" ? undefined : u.status,
    mfaState: u.mfa.state === "reset" ? "reset" : undefined,
    extraRoles: u.roles.slice(1),
    grantedBy: u.roles[0]?.grantedBy,
  }));
  add("userMeta", meta, (m) => m.id);
  if (!existing.has("u-bootstrap"))
    await db
      .insert(users)
      .values({
        userId: "u-bootstrap",
        name: "Bootstrap admin",
        email: "admin@hebuza.example",
        phoneE164: null,
        passwordHash: "!seed-no-login",
        role: "staff:admin",
        isActive: true,
        isEmailVerified: true,
        language: "en",
        createdAt: "2026-01-01T00:00:00Z",
        updatedAt: now,
      })
      .onConflictDoNothing();

  // Identity checks arrive through POST /api/auth/team/access-request (team_access_requests).
  const emails = Object.fromEntries(
    (await db.select({ id: users.userId, email: users.email }).from(users)).map(
      (r) => [r.id, r.email],
    ),
  );
  await db
    .insert(teamAccessRequests)
    .values(
      W.IDENTITY.map((r) => ({
        id: `tar_seed_${r.id.toLowerCase()}`,
        reference: r.id,
        email: String(emails[uid(r.userId)] ?? `${r.userId}@hebuza.example`),
        kind: r.kind,
        note: r.reason,
        status: "open",
        createdAt: r.at,
      })),
    )
    .onConflictDoNothing();
  add(
    "identityMeta",
    W.IDENTITY.map((r) => ({
      id: `tar_seed_${r.id.toLowerCase()}`,
      userId: uid(r.userId),
      managerName: r.managerName,
    })),
    (m) => m.id,
  );

  rows.push({
    kind: "single",
    id: "meta",
    pos: 1,
    data: {
      ...DEFAULT_META,
      counters: { CR: 43, INC: 7, WV: 1, DR: 1 },
      p95: W.P95_MS,
      uptime: W.UPTIME_90,
      slow: [
        { path: "POST /api/cases/{ref}/documents", p95: 812 },
        { path: "GET /api/staff/audit", p95: 640 },
        { path: "POST /api/payments/momo", p95: 590 },
        { path: "GET /api/cases", p95: 402 },
        { path: "POST /api/ai/chat", p95: 388 },
      ],
      // PLACEHOLDER(monitoring-links): real dashboards land with Stage 15.
      links: [
        { label: "Sentry", href: "https://sentry.io/" },
        { label: "Grafana", href: "https://grafana.com/" },
        { label: "Uptime monitor", href: "https://betterstack.com/" },
      ],
    },
  });
  rows.push({
    kind: "single",
    id: "break_glass",
    pos: 1,
    data: { state: "sealed", lastUsedAt: null },
  });
  await db
    .insert(systemRecords)
    .values(rows.map((r) => ({ ...r, updatedAt: now })))
    .onConflictDoNothing();
}

